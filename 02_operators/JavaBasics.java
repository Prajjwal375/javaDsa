import java.util.*;

public class JavaBasics {
    public static void main (String args[]) {
        int A = 10;
        int B = 20;
        System.out.println("A + B = " + (A + B));
        int C = 20;
        int D = ++C;
        System.out.println("C: " + C);
        System.out.println("D: " + D);
    }
}